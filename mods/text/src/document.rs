//! The single-document input/output contract shared by the operations.
//!
//! A document arrives as either an asset path (`doc`) or inline text
//! (`text`), never both, and the result mirrors that form.

use std::path::Path;

use mod_sdk::diagnostic::{Diagnostic, caller_error, internal_error};
use mod_sdk::serde_json::{Map, Value};

use crate::ID;

/// The largest inline document, in UTF-8 bytes. Inline text enters step
/// records, so it is bounded; larger documents must be assets.
pub const MAX_INLINE_BYTES: usize = 256 * 1024;

/// How the caller supplied the document; the result uses the same form.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Form {
    /// A file the host resolved from an asset; the result is a new `.md` file.
    Asset,
    /// Inline text; the result is inline text.
    Inline,
}

/// A loaded input document.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Document {
    pub text: String,
    pub form: Form,
}

impl Document {
    /// Load the single document from `input`: exactly one of `doc` (an asset
    /// path) and `text` (inline) must be present.
    pub fn load(input: &Value) -> Result<Self, Diagnostic> {
        let doc = input.get("doc").filter(|value| !value.is_null());
        let text = input.get("text").filter(|value| !value.is_null());
        match (doc, text) {
            (Some(_), Some(_)) => Err(caller_error(
                ID,
                "AMBIGUOUS_DOCUMENT",
                "give exactly one of `doc` (an asset) and `text` (inline); both were provided",
            )),
            (None, None) => Err(caller_error(
                ID,
                "MISSING_DOCUMENT",
                "give exactly one of `doc` (an asset) and `text` (inline); neither was provided",
            )),
            (Some(doc), None) => {
                let path = doc.as_str().ok_or_else(|| {
                    caller_error(ID, "INVALID_DOCUMENT", "`doc` must be a string asset path")
                })?;
                let bytes = std::fs::read(path).map_err(|error| {
                    caller_error(
                        ID,
                        "READ_FAILED",
                        format!("failed to read the document at `{path}`: {error}"),
                    )
                })?;
                let text = String::from_utf8(bytes).map_err(|_| {
                    caller_error(
                        ID,
                        "INVALID_UTF8",
                        format!("the document at `{path}` is not valid UTF-8"),
                    )
                })?;
                Ok(Self {
                    text,
                    form: Form::Asset,
                })
            }
            (None, Some(text)) => {
                let text = text.as_str().ok_or_else(|| {
                    caller_error(ID, "INVALID_DOCUMENT", "`text` must be a string")
                })?;
                check_inline(text)?;
                Ok(Self {
                    text: text.to_owned(),
                    form: Form::Inline,
                })
            }
        }
    }
}

/// Reject inline text above [`MAX_INLINE_BYTES`].
pub fn check_inline(text: &str) -> Result<(), Diagnostic> {
    if text.len() > MAX_INLINE_BYTES {
        return Err(caller_error(
            ID,
            "INLINE_TOO_LARGE",
            format!(
                "inline text is {} bytes; the limit is {MAX_INLINE_BYTES} bytes. Use an asset (`doc`) instead",
                text.len()
            ),
        ));
    }
    Ok(())
}

/// Add the result document to `map`: a `.md` file for an asset input, the
/// checked string for an inline input.
pub fn put(
    map: &mut Map<String, Value>,
    form: Form,
    output_dir: &Path,
    name: &str,
    text: &str,
) -> Result<(), Diagnostic> {
    match form {
        Form::Asset => {
            write_asset(output_dir, name, text)?;
            map.insert("doc".to_owned(), Value::String(name.to_owned()));
        }
        Form::Inline => {
            check_inline(text)?;
            map.insert("text".to_owned(), Value::String(text.to_owned()));
        }
    }
    Ok(())
}

/// A result object holding just the document.
pub fn result(form: Form, output_dir: &Path, name: &str, text: &str) -> Result<Value, Diagnostic> {
    let mut map = Map::new();
    put(&mut map, form, output_dir, name, text)?;
    Ok(Value::Object(map))
}

/// Write a result file inside the invocation's output directory. `name` is
/// always a plain relative file name generated by this mod.
pub fn write_asset(output_dir: &Path, name: &str, text: &str) -> Result<(), Diagnostic> {
    if !is_plain_relative_name(name) {
        return Err(internal_error(
            ID,
            "INVALID_OUTPUT_NAME",
            format!("`{name}` is not a plain relative file name"),
        ));
    }
    std::fs::write(output_dir.join(name), text).map_err(|error| {
        internal_error(
            ID,
            "WRITE_FAILED",
            format!("failed to write `{name}`: {error}"),
        )
    })
}

fn is_plain_relative_name(name: &str) -> bool {
    !name.is_empty()
        && !name.contains('/')
        && !name.contains('\\')
        && !name.contains("..")
        && !Path::new(name).is_absolute()
}

#[cfg(test)]
mod tests {
    use mod_sdk::serde_json::json;
    use tempfile::tempdir;

    use super::*;

    #[test]
    fn both_forms_are_ambiguous() {
        let error =
            Document::load(&json!({ "doc": "a.md", "text": "inline" })).expect_err("both forms");
        assert_eq!(error.code().as_str(), "MOD/CALLER_AMBIGUOUS_DOCUMENT");
    }

    #[test]
    fn neither_form_is_missing() {
        let error = Document::load(&json!({})).expect_err("no document");
        assert_eq!(error.code().as_str(), "MOD/CALLER_MISSING_DOCUMENT");

        let error = Document::load(&json!({ "doc": null, "text": null }))
            .expect_err("nulls are not a document");
        assert_eq!(error.code().as_str(), "MOD/CALLER_MISSING_DOCUMENT");
    }

    #[test]
    fn a_non_string_document_is_rejected() {
        let error = Document::load(&json!({ "doc": 7 })).expect_err("non-string doc");
        assert_eq!(error.code().as_str(), "MOD/CALLER_INVALID_DOCUMENT");
        let error = Document::load(&json!({ "text": 7 })).expect_err("non-string text");
        assert_eq!(error.code().as_str(), "MOD/CALLER_INVALID_DOCUMENT");
    }

    #[test]
    fn inline_text_is_capped_by_utf8_bytes() {
        let at_limit = "x".repeat(MAX_INLINE_BYTES);
        assert!(Document::load(&json!({ "text": at_limit })).is_ok());

        let over_limit = "x".repeat(MAX_INLINE_BYTES + 1);
        let error = Document::load(&json!({ "text": over_limit })).expect_err("over the cap");
        assert_eq!(error.code().as_str(), "MOD/CALLER_INLINE_TOO_LARGE");

        // Multi-byte characters count as their UTF-8 length, not one per char.
        let wide = "é".repeat(MAX_INLINE_BYTES / 2 + 1);
        let error = Document::load(&json!({ "text": wide })).expect_err("over the cap");
        assert_eq!(error.code().as_str(), "MOD/CALLER_INLINE_TOO_LARGE");
    }

    #[test]
    fn an_asset_must_be_utf8() {
        let temp = tempdir().expect("temp dir");
        let path = temp.path().join("broken.md");
        std::fs::write(&path, [0xff, 0xfe, 0x00]).expect("write");
        let error = Document::load(&json!({ "doc": path.to_str().expect("utf8 path") }))
            .expect_err("invalid utf8");
        assert_eq!(error.code().as_str(), "MOD/CALLER_INVALID_UTF8");
    }

    #[test]
    fn an_asset_is_read_and_its_result_is_a_file() {
        let temp = tempdir().expect("temp dir");
        let path = temp.path().join("input.md");
        std::fs::write(&path, "héllo").expect("write");
        let document =
            Document::load(&json!({ "doc": path.to_str().expect("utf8 path") })).expect("load");
        assert_eq!(document.text, "héllo");
        assert_eq!(document.form, Form::Asset);

        let result = result(document.form, temp.path(), "output.md", "out").expect("result");
        assert_eq!(result, json!({ "doc": "output.md" }));
        assert_eq!(
            std::fs::read_to_string(temp.path().join("output.md")).expect("read"),
            "out"
        );
    }

    #[test]
    fn an_inline_result_is_the_checked_string() {
        let temp = tempdir().expect("temp dir");
        let inline = result(Form::Inline, temp.path(), "output.md", "out").expect("result");
        assert_eq!(inline, json!({ "text": "out" }));
        assert!(!temp.path().join("output.md").exists());

        let oversized = "x".repeat(MAX_INLINE_BYTES + 1);
        let error = result(Form::Inline, temp.path(), "output.md", &oversized)
            .expect_err("output over the cap");
        assert_eq!(error.code().as_str(), "MOD/CALLER_INLINE_TOO_LARGE");
    }

    #[test]
    fn output_names_must_be_plain_relative_names() {
        let temp = tempdir().expect("temp dir");
        for name in ["../output.md", "dir/output.md", "/tmp/output.md", ".."] {
            let error = write_asset(temp.path(), name, "x").expect_err("unsafe name");
            assert_eq!(error.code().as_str(), "MOD/INTERNAL_INVALID_OUTPUT_NAME");
        }
    }
}
