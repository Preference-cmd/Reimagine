//! Append-only project activity log.
//!
//! Every board apply/undo/redo and every recorded operation step appends one
//! record to `projects/{project_id}/activity.jsonl`. Rows are read back
//! newest-first through [`ActivityService::list`] (the `activity.list` kernel
//! operation) and pushed live as `activity.appended` events.

use std::collections::BTreeMap;
use std::io::SeekFrom;
use std::path::PathBuf;
use std::sync::Arc;
use std::sync::atomic::{AtomicU64, Ordering};

use async_trait::async_trait;
use mod_sdk::{OperationAnnotations, OperationSpec};
use reimagine_config::AppPaths;
use reimagine_core::command::CommandActor;
use reimagine_core::diagnostic::{
    Diagnostic, DiagnosticCode, DiagnosticSeverity, DiagnosticSourceName, DiagnosticTarget,
    DiagnosticTargetDomain,
};
use reimagine_core::event::{Event, EventBus};
use reimagine_core::model::{DiagnosticId, HistoryEntryId, ProjectId};
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use tokio::io::{AsyncReadExt, AsyncSeekExt, AsyncWriteExt};

use crate::error::{AppHostError, AppHostResult};
use crate::operation_service::{KernelCall, KernelOp, OperationService};

/// Default page size for `activity.list`.
pub const ACTIVITY_LIST_DEFAULT_LIMIT: usize = 50;
/// Largest page `activity.list` accepts.
pub const ACTIVITY_LIST_MAX_LIMIT: usize = 200;

fn activity_internal_error(code: &str, message: impl Into<String>) -> Diagnostic {
    Diagnostic::new(
        DiagnosticId::new(format!("activity:{code}")),
        DiagnosticCode::new(format!("ACTIVITY/INTERNAL_{code}")),
        DiagnosticSeverity::Error,
        DiagnosticSourceName::new("activity"),
        message,
        DiagnosticTarget::new(DiagnosticTargetDomain::new("activity")),
    )
}

/// What an activity record describes.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ActivityKind {
    Applied,
    Undone,
    Redone,
    RunStarted,
    RunFinished,
    RunCancelled,
}

/// One append-only activity record.
///
/// `summary` is generated by the operation that produced the record (English
/// fallback); `summary_key` + `summary_params` let clients render it in their
/// own language. `targets` are the board item ids the record touched.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ActivityRecord {
    pub id: String,
    /// RFC 3339 timestamp.
    pub at: String,
    pub actor: CommandActor,
    pub summary: String,
    pub summary_key: String,
    pub summary_params: Value,
    pub targets: Vec<String>,
    pub kind: ActivityKind,
    pub history_entry_id: Option<HistoryEntryId>,
}

/// `<project>/activity.jsonl`: one JSON record plus a newline per append.
#[derive(Debug)]
pub struct ActivityLog {
    project_dir: PathBuf,
    append_lock: tokio::sync::Mutex<()>,
}

impl ActivityLog {
    pub fn new(project_dir: impl Into<PathBuf>) -> Self {
        Self {
            project_dir: project_dir.into(),
            append_lock: tokio::sync::Mutex::new(()),
        }
    }

    pub fn activity_jsonl_path(&self) -> PathBuf {
        self.project_dir.join("activity.jsonl")
    }

    /// Append one record, repairing a torn trailing line first.
    ///
    /// A process abort can leave a partial line. Appending after it would
    /// merge the partial record and the new one into a single malformed line,
    /// hiding both from [`Self::read`].
    async fn append(&self, record: &ActivityRecord) -> AppHostResult<()> {
        let _guard = self.append_lock.lock().await;

        let path = self.activity_jsonl_path();
        if let Some(parent) = path.parent() {
            tokio::fs::create_dir_all(parent)
                .await
                .map_err(|error| AppHostError::Io {
                    path: parent.to_path_buf(),
                    message: error.to_string(),
                })?;
        }

        let mut file = tokio::fs::OpenOptions::new()
            .create(true)
            .read(true)
            .append(true)
            .open(&path)
            .await
            .map_err(|error| AppHostError::Io {
                path: path.clone(),
                message: error.to_string(),
            })?;

        Self::truncate_torn_tail(&mut file, &path).await?;

        let line = serde_json::to_string(record).map_err(|error| AppHostError::Io {
            path: path.clone(),
            message: format!("failed to serialize activity record: {error}"),
        })?;

        file.write_all(format!("{line}\n").as_bytes())
            .await
            .map_err(|error| AppHostError::Io {
                path: path.clone(),
                message: error.to_string(),
            })?;
        file.flush().await.map_err(|error| AppHostError::Io {
            path: path.clone(),
            message: error.to_string(),
        })?;

        Ok(())
    }

    /// Truncate the file to its last complete line. A file without any
    /// newline is a single torn record and is emptied.
    async fn truncate_torn_tail(
        file: &mut tokio::fs::File,
        path: &std::path::Path,
    ) -> AppHostResult<()> {
        let io_error = |message: String| AppHostError::Io {
            path: path.to_path_buf(),
            message,
        };

        let len = file
            .metadata()
            .await
            .map_err(|error| io_error(error.to_string()))?
            .len();
        if len == 0 {
            return Ok(());
        }

        let mut buffer = [0u8; 8192];
        let mut end = len;
        while end > 0 {
            let start = end.saturating_sub(buffer.len() as u64);
            let chunk_len = (end - start) as usize;
            file.seek(SeekFrom::Start(start))
                .await
                .map_err(|error| io_error(error.to_string()))?;
            file.read_exact(&mut buffer[..chunk_len])
                .await
                .map_err(|error| io_error(error.to_string()))?;
            if let Some(index) = buffer[..chunk_len].iter().rposition(|byte| *byte == b'\n') {
                let keep = start + index as u64 + 1;
                if keep < len {
                    file.set_len(keep)
                        .await
                        .map_err(|error| io_error(error.to_string()))?;
                }
                return Ok(());
            }
            end = start;
        }

        file.set_len(0)
            .await
            .map_err(|error| io_error(error.to_string()))?;
        Ok(())
    }

    /// Records in append order. A torn trailing line and malformed complete
    /// lines are skipped: one bad line must not hide the rest of the history.
    pub async fn read(&self) -> AppHostResult<Vec<ActivityRecord>> {
        let path = self.activity_jsonl_path();
        let content = match tokio::fs::read_to_string(&path).await {
            Ok(content) => content,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
            Err(error) => {
                return Err(AppHostError::Io {
                    path,
                    message: error.to_string(),
                });
            }
        };

        Ok(content
            .lines()
            .filter(|line| !line.trim().is_empty())
            .filter_map(|line| serde_json::from_str::<ActivityRecord>(line).ok())
            .collect())
    }
}

/// Per-project activity logs plus the `activity.appended` event publisher.
#[derive(Debug)]
pub struct ActivityService {
    paths: AppPaths,
    event_bus: EventBus,
    logs: tokio::sync::Mutex<BTreeMap<ProjectId, Arc<ActivityLog>>>,
    next_id: AtomicU64,
}

impl ActivityService {
    pub fn new(paths: AppPaths, event_bus: EventBus) -> Self {
        Self {
            paths,
            event_bus,
            logs: tokio::sync::Mutex::new(BTreeMap::new()),
            next_id: AtomicU64::new(1),
        }
    }

    async fn log_for(&self, project_id: &ProjectId) -> Arc<ActivityLog> {
        let mut logs = self.logs.lock().await;
        logs.entry(project_id.clone())
            .or_insert_with(|| {
                Arc::new(ActivityLog::new(
                    self.paths.project_dir(project_id.as_str()),
                ))
            })
            .clone()
    }

    /// Append one record and publish `activity.appended`.
    ///
    /// The event carries `{ projectId, record }` under the core `mod` event
    /// shape, so core stays independent of app-host types.
    #[allow(clippy::too_many_arguments)]
    pub async fn record(
        &self,
        project_id: &ProjectId,
        kind: ActivityKind,
        actor: CommandActor,
        summary: impl Into<String>,
        summary_key: impl Into<String>,
        summary_params: Value,
        targets: Vec<String>,
        history_entry_id: Option<HistoryEntryId>,
    ) -> AppHostResult<ActivityRecord> {
        let count = self.next_id.fetch_add(1, Ordering::Relaxed);
        let now = chrono::Utc::now();
        let nanos = now.timestamp_nanos_opt().unwrap_or_default();
        let record = ActivityRecord {
            id: format!("act-{nanos:x}-{count:x}"),
            at: now.to_rfc3339(),
            actor,
            summary: summary.into(),
            summary_key: summary_key.into(),
            summary_params,
            targets,
            kind,
            history_entry_id,
        };

        self.log_for(project_id).await.append(&record).await?;

        self.event_bus.publish(Event::mod_event(
            "activity.appended",
            json!({ "projectId": project_id.as_str(), "record": record }),
        ));

        Ok(record)
    }

    /// One page of records, newest first.
    ///
    /// `before` is the id of the last record of the previous page; paging
    /// starts after it. An unknown id starts from the newest record.
    /// `has_more` reports whether older records remain after this page.
    pub async fn list(
        &self,
        project_id: &ProjectId,
        before: Option<&str>,
        limit: usize,
    ) -> AppHostResult<(Vec<ActivityRecord>, bool)> {
        let mut records = self.log_for(project_id).await.read().await?;
        records.reverse();

        let start = match before {
            Some(before) => records
                .iter()
                .position(|record| record.id == before)
                .map_or(0, |index| index + 1),
            None => 0,
        };
        let remaining = records.len().saturating_sub(start);
        let page = records.into_iter().skip(start).take(limit).collect();
        Ok((page, remaining > limit))
    }
}

/// The built-in `activity.list` kernel operation.
pub struct ActivityListOp {
    spec: OperationSpec,
    activity_service: Arc<ActivityService>,
}

impl ActivityListOp {
    pub fn new(activity_service: Arc<ActivityService>) -> Self {
        Self {
            spec: OperationSpec {
                name: "activity.list".to_owned(),
                description:
                    "List project activity records, newest first, paged with a record-id cursor"
                        .to_owned(),
                input_schema: json!({
                    "type": "object",
                    "properties": {
                        "before": {
                            "type": "string",
                            "description": "Id of the last record of the previous page."
                        },
                        "limit": {
                            "type": "integer",
                            "minimum": 1,
                            "maximum": ACTIVITY_LIST_MAX_LIMIT,
                            "default": ACTIVITY_LIST_DEFAULT_LIMIT
                        }
                    },
                    "additionalProperties": false
                }),
                output_schema: json!({
                    "type": "object",
                    "properties": {
                        "records": {
                            "type": "array",
                            "items": {
                                "type": "object",
                                "properties": {
                                    "id": { "type": "string" },
                                    "at": { "type": "string" },
                                    "actor": {
                                        "type": "object",
                                        "properties": {
                                            "kind": {
                                                "type": "string",
                                                "enum": ["Human", "Agent", "Importer", "System"]
                                            },
                                            "id": { "type": ["string", "null"] },
                                            "label": { "type": ["string", "null"] }
                                        },
                                        "required": ["kind", "id", "label"]
                                    },
                                    "summary": { "type": "string" },
                                    "summaryKey": { "type": "string" },
                                    "summaryParams": {},
                                    "targets": {
                                        "type": "array",
                                        "items": { "type": "string" }
                                    },
                                    "kind": {
                                        "type": "string",
                                        "enum": [
                                            "applied",
                                            "undone",
                                            "redone",
                                            "run_started",
                                            "run_finished",
                                            "run_cancelled"
                                        ]
                                    },
                                    "historyEntryId": { "type": ["string", "null"] }
                                },
                                "required": [
                                    "id",
                                    "at",
                                    "actor",
                                    "summary",
                                    "summaryKey",
                                    "summaryParams",
                                    "targets",
                                    "kind",
                                    "historyEntryId"
                                ]
                            }
                        },
                        "has_more": { "type": "boolean" }
                    },
                    "required": ["records", "has_more"],
                    "additionalProperties": false,
                    "examples": [{ "records": [], "has_more": false }]
                }),
                annotations: OperationAnnotations {
                    read_only: true,
                    destructive: false,
                    idempotent: true,
                    deterministic: true,
                    open_world: false,
                },
            },
            activity_service,
        }
    }
}

#[async_trait]
impl KernelOp for ActivityListOp {
    fn spec(&self) -> &OperationSpec {
        &self.spec
    }

    async fn invoke(&self, call: KernelCall) -> Result<Value, Diagnostic> {
        let before = call.caller_input.get("before").and_then(Value::as_str);
        let limit = call
            .caller_input
            .get("limit")
            .and_then(Value::as_u64)
            .and_then(|limit| usize::try_from(limit).ok())
            .unwrap_or(ACTIVITY_LIST_DEFAULT_LIMIT)
            .clamp(1, ACTIVITY_LIST_MAX_LIMIT);

        let (records, has_more) = self
            .activity_service
            .list(&call.project_id, before, limit)
            .await
            .map_err(|error| activity_internal_error("LIST_FAILED", error.to_string()))?;

        Ok(json!({ "records": records, "has_more": has_more }))
    }
}

/// Register the activity operations with an [`OperationService`].
pub fn register_activity_ops(
    op_service: &OperationService,
    activity_service: Arc<ActivityService>,
) {
    op_service.register_kernel_op(Arc::new(ActivityListOp::new(activity_service)));
}
